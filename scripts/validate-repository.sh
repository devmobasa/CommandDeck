#!/usr/bin/env bash
set -euo pipefail

repo_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
cd "$repo_dir"

# The baseline is a repository-owned data file; the validation command does
# not use shellcheck -x, so it is checked through its consuming script only.
# shellcheck disable=SC1091
source scripts/validation-baseline.env

validation_tmp=$(mktemp -d)
trap 'rm -rf -- "$validation_tmp"' EXIT

run_log() {
  local name=$1
  shift
  "$@" 2>&1 | tee "$validation_tmp/$name.log"
}

run_log restore dotnet restore CommandDeck.slnx --locked-mode
run_log build dotnet build CommandDeck.slnx --configuration Release --no-restore
run_log format dotnet format CommandDeck.slnx --verify-no-changes --no-restore
run_log backend dotnet run \
  --project tests/CommandDeck.Specs/CommandDeck.Specs.csproj \
  --configuration Release \
  --no-build \
  -- --results "$repo_dir/build/backend-spec-results.json"
run_log quality "$repo_dir/scripts/quality-gate.sh"
run_log reset_config "$repo_dir/tests/reset-local-config.sh"

backend_count=$(grep -c '^PASS ' "$validation_tmp/backend.log")
backend_skipped_count=$(grep -c '^SKIP ' "$validation_tmp/backend.log" || true)
backend_discovered_count=$((backend_count + backend_skipped_count))
reported_backend_count=$(sed -n \
  's/^Executed \([0-9][0-9]*\) CommandDeck specs\.$/\1/p' \
  "$validation_tmp/backend.log")
test "$backend_count" -gt 0
# Partial and AOT environments may explicitly skip optional native tools.
# Keep the inventory floor intact without counting those skips as passes.
test "$backend_discovered_count" -ge "$BACKEND_SPEC_MINIMUM"
test "$reported_backend_count" = "$backend_count"
test -s "$repo_dir/build/backend-spec-results.json"

plugin_status=unavailable
if command -v omarchy >/dev/null; then
  run_log plugin omarchy plugin validate "$repo_dir/qml"
  plugin_status=passed
fi

# The QML script lints every QML file, runs both suites, and enforces their
# floors. Without Quickshell the partial profile records zero counts.
qml_lint_count=0
qml_component_count=0
qml_event_count=0
if command -v qs >/dev/null; then
  run_log qml "$repo_dir/scripts/test-qml-components.sh"
  qml_counts=$(grep '^QML_COUNT ' "$validation_tmp/qml.log")
  qml_lint_count=$(sed -n 's/.* lint=\([0-9][0-9]*\).*/\1/p' <<<"$qml_counts")
  qml_component_count=$(sed -n 's/.* component=\([0-9][0-9]*\).*/\1/p' <<<"$qml_counts")
  qml_event_count=$(sed -n 's/.* event=\([0-9][0-9]*\).*/\1/p' <<<"$qml_counts")
  test "$qml_lint_count" -gt 0
fi

shell_status=unavailable
shell_count=0
privileged_scripts=("$repo_dir/scripts/install-system-helper.sh" "$repo_dir/scripts/uninstall-system-helper.sh")
if command -v shellcheck >/dev/null; then
  shellcheck "$repo_dir"/scripts/*.sh
  shell_count=$(find "$repo_dir/scripts" -maxdepth 1 -type f -name '*.sh' | wc -l)
  shell_status=passed
else
  for privileged_script in "${privileged_scripts[@]}"; do
    if [[ -f $privileged_script ]]; then
      printf 'error: %s exists but shellcheck is not installed; install shellcheck to validate privileged scripts.\n' \
        "$privileged_script" >&2
      exit 1
    fi
  done
fi

git diff --check

# Fresh review repositories intentionally have no commits. Keep the real source
# digest below as their identity instead of failing report generation.
commit=$(git rev-parse --verify HEAD 2>/dev/null || printf 'unborn (no commit)')
branch=$(git branch --show-current)
tracked_status=$(git status --porcelain=v1 --untracked-files=all |
  grep -v '^?? build/validation-report.md$' || true)
if [[ -n $tracked_status ]]; then
  tree_state=dirty
else
  tree_state=clean
fi

snapshot_digest=$(
  git ls-files -co --exclude-standard -z |
    sort -z |
    while IFS= read -r -d '' snapshot_path; do
      if [[ $snapshot_path == build/validation-report.md ]]; then
        continue
      fi
      if [[ -L $snapshot_path ]]; then
        {
          printf 'symlink\0%s\0' "$snapshot_path"
          readlink -z -- "$snapshot_path"
        } | sha256sum
      elif [[ -f $snapshot_path ]]; then
        sha256sum -- "$snapshot_path"
      fi
    done |
    sha256sum |
    cut -d' ' -f1
)
validated_at=$(date --utc +'%Y-%m-%dT%H:%M:%SZ')
dotnet_version=$(dotnet --version)
kernel=$(uname -sr)
architecture=$(uname -m)
omarchy_version=$(pacman -Q omarchy 2>/dev/null || printf 'unavailable')
qs_version=$(qs --version 2>/dev/null | head -1 || printf 'unavailable')
qt_version=$(/usr/lib/qt6/bin/qmllint --version 2>/dev/null | head -1 || printf 'unavailable')

report_tmp="$validation_tmp/validation-report.md"
# Backticks in this block are intentional literal Markdown delimiters.
# shellcheck disable=SC2016
{
  printf '# Generated validation report\n\n'
  printf 'Generated by `scripts/validate-repository.sh` from one uninterrupted run.\n\n'
  printf '## Snapshot\n\n'
  printf -- '- Validated at: `%s`\n' "$validated_at"
  printf -- '- Commit: `%s`\n' "$commit"
  printf -- '- Branch: `%s`\n' "${branch:-detached}"
  printf -- '- Working tree: `%s`\n' "$tree_state"
  printf -- '- Source snapshot SHA-256: `%s`\n' "$snapshot_digest"
  printf '\n## Environment\n\n'
  printf -- '- .NET SDK: `%s`\n' "$dotnet_version"
  printf -- '- Kernel: `%s`\n' "$kernel"
  printf -- '- Architecture: `%s`\n' "$architecture"
  printf -- '- Omarchy: `%s`\n' "$omarchy_version"
  printf -- '- Quickshell: `%s`\n' "$qs_version"
  printf -- '- Qt/QML lint: `%s`\n' "$qt_version"
  printf '\n## Executed gates\n\n'
  printf -- '- Locked restore: passed\n'
  printf -- '- Release build: passed with 0 warnings and 0 errors\n'
  printf -- '- Formatting verification: passed\n'
  if [[ ${COMMANDDECK_QUALITY_LATENCY_MODE:-enforce} == observe ]]; then
    printf -- '- Quality gate: ranking, allocation, and database size passed; hosted latency observed in quality-metrics.json\n'
  else
    printf -- '- Machine-readable ranking/performance quality budgets: passed\n'
  fi
  printf -- '- Backend executable specs: %s passed, %s skipped; %s discovered (minimum %s)\n' \
    "$backend_count" "$backend_skipped_count" "$backend_discovered_count" "$BACKEND_SPEC_MINIMUM"
  printf -- '- Plugin validation: %s\n' "$plugin_status"
  printf -- '- QML files linted: %s\n' "$qml_lint_count"
  printf -- '- QML component assertions: %s passed (minimum %s)\n' \
    "$qml_component_count" "$QML_COMPONENT_SPEC_MINIMUM"
  printf -- '- Named real-event QML tests: %s passed (minimum %s)\n' \
    "$qml_event_count" "$QML_EVENT_SPEC_MINIMUM"
  printf -- '- Shell validation: %s (%s scripts checked)\n' "$shell_status" "$shell_count"
  printf -- '- Diff whitespace validation: passed\n'
  printf '\n## Scope\n\n'
  printf 'This gate intentionally excludes packaging, publishing, installation, upgrade, and rollback.\n'
} >"$report_tmp"

mv "$report_tmp" "$repo_dir/build/validation-report.md"
printf 'Validation report: %s\n' "$repo_dir/build/validation-report.md"
