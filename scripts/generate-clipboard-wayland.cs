#!/usr/bin/env dotnet
#:property RestorePackagesWithLockFile=false

using System.Security.Cryptography;
using System.Text;
using System.Xml.Linq;

var root = Directory.GetCurrentDirectory( );
var xmlPath = Path.Combine( root, "third_party/wayland/ext-data-control-v1.xml" );

var outputPath = Path.Combine( root, "src/CommandDeck.Infrastructure/Clipboard/Native/ClipboardWaylandDefinitions.g.cs" );

var bytes = File.ReadAllBytes( xmlPath );
var digest = Convert.ToHexStringLower( SHA256.HashData( bytes ) );

if ( digest != "293deba5dfdb974fbcf8dcf891a30a51a36a8bba0047dc6bdf6a03194089b7fb" )
{
    throw new InvalidDataException( "Clipboard Wayland XML changed; review and pin its protocol before regenerating." );
}

var xml = XDocument.Parse( Encoding.UTF8.GetString( bytes ) );
StringBuilder output = new( );
output.AppendLine( "// <auto-generated/>" );
output.AppendLine( "// Generated by scripts/generate-clipboard-wayland.cs from third_party/wayland/ext-data-control-v1.xml." );
output.AppendLine( "// Protocol copyright and MIT license are preserved in that XML file." );
output.AppendLine( "// SHA-256: " + digest );
output.AppendLine( "namespace CommandDeck;" );
output.AppendLine( "internal static class ClipboardWaylandDefinitions" );
output.AppendLine( "{" );
output.AppendLine( "    public static readonly WaylandInterfaceDefinition[] Interfaces =" );
output.AppendLine( "    [" );

foreach ( var definition in xml.Root!.Elements( "interface" ) )
{
    output.AppendLine( $"        new(\"{definition.Attribute( "name" )!.Value}\", {definition.Attribute( "version" )!.Value}," );

    WaylandGenerator.AppendMessages( output, definition.Elements( "request" ) );
    output.AppendLine( "," );
    WaylandGenerator.AppendMessages( output, definition.Elements( "event" ) );
    output.AppendLine( ")," );
}

output.AppendLine( "    ];" );
output.AppendLine( "}" );

var generated = output
    .ToString( )
    .Replace( "\r\n", "\n", StringComparison.Ordinal );

if ( args.Contains( "--check", StringComparer.Ordinal ) )
{
    if ( NeedsRegeneration( outputPath, generated ) )
    {
        throw new InvalidDataException( "Generated clipboard Wayland metadata is stale." );
    }
}
else
{
    Directory.CreateDirectory( Path.GetDirectoryName( outputPath )! );
    File.WriteAllText( outputPath, generated );
}

Console.WriteLine( "Clipboard Wayland metadata matches pinned XML." );

static bool NeedsRegeneration( string outputPath, string generated )
{
    return !File.Exists( outputPath ) || File.ReadAllText( outputPath ) != generated;
}

static class WaylandGenerator
{
    public static void AppendMessages( StringBuilder output, IEnumerable<XElement> messages )
    {
        output.AppendLine( "        [" );

        foreach ( var message in messages )
        {
            var arguments = message
                .Elements( "arg" )
                .ToArray( );
            var since = message.Attribute( "since" )?.Value;
            var signature = since is null or "1" ? "" : since;

            foreach ( var argument in arguments )
            {
                if ( argument.Attribute( "allow-null" )?.Value == "true" )
                {
                    signature += "?";
                }

                signature += ArgumentSignature( argument.Attribute( "type" )!.Value );
            }

            var types = string.Join( ", ", arguments.Select( argument => argument.Attribute( "interface" ) is { } name ? "\"" + name.Value + "\"" : "null" ) );

            output.AppendLine( $"            new(\"{message.Attribute( "name" )!.Value}\", \"{signature}\", [{types}])," );
        }

        output.Append( "        ]" );
    }

    private static string ArgumentSignature( string type )
    {
        switch ( type )
        {
            case "int":
                return "i";
            case "uint":
                return "u";
            case "fixed":
                return "f";
            case "string":
                return "s";
            case "object":
                return "o";
            case "new_id":
                return "n";
            case "array":
                return "a";
            case "fd":
                return "h";
            default:
                throw new InvalidDataException( "Unknown Wayland argument type." );
        }
    }
}
