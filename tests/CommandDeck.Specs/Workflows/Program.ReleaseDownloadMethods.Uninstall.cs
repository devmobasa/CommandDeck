namespace CommandDeck.Specs;

public static partial class Program
{
    private const string GeneratedHotkeyHeader = "-- Generated by `commanddeck hotkey install`.\n";
    private const string GeneratedKeysHeader = "-- Generated by CommandDeck. Edit through Settings → Shortcuts.\n";

    // Uninstall removes only what the installer created, keeps configuration,
    // state, and files it does not own, and changes nothing until the daemon
    // has stopped and the desktop can take each step.
    private static async Task ReleaseDownloaderUninstallsOnlyWhatItInstalledAsync( )
    {
        if ( !OperatingSystem.IsLinux( ) )
        {
            throw new SpecSkippedException( "This fixture requires Linux." );
        }

        var root = SpecTemporaryFiles.CreateDirectory( "commanddeck-uninstall-" ).FullName;

        try
        {
            // A complete installation: a dry run changes nothing, then the
            // uninstall removes it, and a second run finds nothing.
            var fixture = await CreateDownloadFixtureAsync( Directory.CreateDirectory( Path.Combine( root, "complete" ) ).FullName );
            var seeded = await SeedInstallationAsync( fixture, fixture.State );

            var dryRun = await RunDownloaderAsync( fixture, ["--uninstall", "--dry-run"], "x86_64", "ok" );
            Equal( 0, dryRun.ExitCode );
            True( dryRun.StandardOutput.Contains( "Dry run", StringComparison.Ordinal ), dryRun.StandardOutput );
            True( seeded.Removed.All( File.Exists ), "the dry run changes nothing" );
            var checks = await File.ReadAllTextAsync( fixture.Calls + ".tools" );
            string[] changes = ["stop", "hotkey", "disable", "reload", "restart"];
            True( !changes.Any( word => checks.Contains( word, StringComparison.Ordinal ) ), "the dry run only checks: " + checks );

            var uninstall = await RunDownloaderAsync( fixture, ["--uninstall"], "x86_64", "ok" );
            Equal( 0, uninstall.ExitCode );
            True( seeded.Removed.All( file => !File.Exists( file ) ), "the installed files are removed: " + uninstall.StandardOutput );
            True( seeded.Kept.All( File.Exists ), "configuration, state, and files CommandDeck did not generate are kept" );
            True( !Directory.Exists( seeded.Program ), "the emptied program folder is removed" );
            True( new FileInfo( seeded.Link ).LinkTarget is null, "the command link is removed" );
            var backups = Path.Combine( fixture.State, "commanddeck", "plugin-backups" );
            True( Directory.EnumerateFiles( backups, "manifest.json", SearchOption.AllDirectories ).Any( ), "the plugin moves to the plugin backups" );

            var tools = await File.ReadAllTextAsync( fixture.Calls + ".tools" );
            string[] calls =
            [
                "systemctl --user stop commanddeck.service", "commanddeck hotkey remove", "hyprctl reload",
                "omarchy plugin disable local.commanddeck", "systemctl --user daemon-reload", "omarchy restart shell"
            ];
            True( calls.All( call => tools.Contains( call, StringComparison.Ordinal ) ), tools );
            True( tools.IndexOf( "systemctl --user stop", StringComparison.Ordinal ) < tools.IndexOf( "hotkey remove", StringComparison.Ordinal ),
                "the daemon stops before the hotkey goes" );

            var again = await RunDownloaderAsync( fixture, ["--uninstall"], "x86_64", "ok" );
            Equal( 0, again.ExitCode );
            True( again.StandardOutput.Contains( "not installed", StringComparison.Ordinal ), again.StandardOutput );
            Equal( 2, (await RunDownloaderAsync( fixture, ["--uninstall", "--force"], "x86_64", "ok" )).ExitCode );

            // Each step that cannot run stops the uninstall: a check stops it
            // before any change, and a failed step before any removal.
            fixture = await CreateDownloadFixtureAsync( Directory.CreateDirectory( Path.Combine( root, "blocked" ) ).FullName );
            seeded = await SeedInstallationAsync( fixture, fixture.State );
            (string Environment, string Error)[] blocked =
            [
                ("COMMANDDECK_SPEC_SERVICE_ACTIVE=1", "did not stop"), ("COMMANDDECK_SPEC_SYSTEMD_DOWN=1", "not reachable"),
                ("COMMANDDECK_SPEC_HYPRLAND_DOWN=1", "hyprctl cannot reach it"),
                ("COMMANDDECK_SPEC_OMARCHY_LIST_FAIL=1", "did not list its plugins")
            ];
            foreach ( var (environment, error) in blocked )
            {
                var result = await RunDownloaderAsync( fixture, ["--uninstall"], "x86_64", "ok", [environment] );
                Equal( 1, result.ExitCode );
                True( result.StandardError.Contains( error, StringComparison.Ordinal ), environment + ": " + result.StandardError );
                True( seeded.Removed.All( File.Exists ), environment + " removes nothing" );
            }

            // Without systemctl, nothing can stop the daemon. The PATH here has
            // only what the script needs before that check.
            var restricted = Directory.CreateDirectory( Path.Combine( fixture.Root, "restricted" ) ).FullName;
            File.CreateSymbolicLink( Path.Combine( restricted, "uname" ), Path.Combine( fixture.Tools, "uname" ) );
            File.CreateSymbolicLink( Path.Combine( restricted, "readlink" ), File.Exists( "/usr/bin/readlink" ) ? "/usr/bin/readlink" : "/bin/readlink" );
            var noSystemctl = await RunDownloaderAsync( fixture, ["--uninstall"], "x86_64", "ok", ["PATH=" + restricted], command: ["/bin/bash"] );
            Equal( 1, noSystemctl.ExitCode );
            True( noSystemctl.StandardError.Contains( "systemctl is missing", StringComparison.Ordinal ), noSystemctl.StandardError );
            True( seeded.Removed.All( File.Exists ), "a missing systemctl removes nothing" );

            var disable = await RunDownloaderAsync( fixture, ["--uninstall"], "x86_64", "ok", ["COMMANDDECK_SPEC_OMARCHY_FAIL=1"] );
            Equal( 1, disable.ExitCode );
            True( disable.StandardError.Contains( "plugin disable", StringComparison.Ordinal ), disable.StandardError );
            True( File.Exists( seeded.Binary ) && Directory.Exists( seeded.Plugin ) && File.Exists( seeded.Service ),
                "a failed plugin disable keeps the plugin, the service file, and the program" );

            // A missing binary: the generated hotkey module still goes, so the
            // binding cannot outlive the installation.
            fixture = await CreateDownloadFixtureAsync( Directory.CreateDirectory( Path.Combine( root, "no-binary" ) ).FullName );
            seeded = await SeedInstallationAsync( fixture, fixture.State, "missing" );
            var noBinary = await RunDownloaderAsync( fixture, ["--uninstall"], "x86_64", "ok" );
            Equal( 0, noBinary.ExitCode );
            True( !File.Exists( Path.Combine( seeded.Hypr, "commanddeck.lua" ) ), "the generated hotkey module is removed" );
            True( noBinary.StandardOutput.Contains( "binary is missing", StringComparison.Ordinal ), noBinary.StandardOutput );
            True( seeded.Kept.All( File.Exists ), "configuration and state are kept" );
            True( (await RunDownloaderAsync( fixture, ["--uninstall"], "x86_64", "ok" )).StandardOutput.Contains( "not installed", StringComparison.Ordinal ),
                "nothing is left to find" );

            // A generated backup alone still counts as an installation leftover.
            var leftover = Path.Combine( seeded.Hypr, "commanddeck_keys.lua.bak" );
            await File.WriteAllTextAsync( leftover, GeneratedKeysHeader );
            Equal( 0, (await RunDownloaderAsync( fixture, ["--uninstall"], "x86_64", "ok" )).ExitCode );
            True( !File.Exists( leftover ), "the generated backup is removed" );

            // A binary that exists but cannot run: the generated module still
            // goes, and the uninstall finishes instead of failing every retry.
            fixture = await CreateDownloadFixtureAsync( Directory.CreateDirectory( Path.Combine( root, "broken-binary" ) ).FullName );
            seeded = await SeedInstallationAsync( fixture, fixture.State, "broken" );
            var broken = await RunDownloaderAsync( fixture, ["--uninstall"], "x86_64", "ok" );
            Equal( 0, broken.ExitCode );
            True( seeded.Removed.All( file => !File.Exists( file ) ), "the installed files are removed: " + broken.StandardOutput + broken.StandardError );
            True( broken.StandardOutput.Contains( "does not run", StringComparison.Ordinal ), broken.StandardOutput );

            // State in the program folder, and files the installer did not list:
            // they stay, and so does the folder.
            fixture = await CreateDownloadFixtureAsync( Directory.CreateDirectory( Path.Combine( root, "shared" ) ).FullName );
            seeded = await SeedInstallationAsync( fixture, fixture.Data );
            string[] foreign = [Path.Combine( seeded.Program, "custom.so" ), Path.Combine( seeded.Program, "picker", "notes.txt" )];
            foreach ( var file in foreign )
            {
                await File.WriteAllTextAsync( file, "mine" );
            }

            var shared = await RunDownloaderAsync( fixture, ["--uninstall"], "x86_64", "ok", ["XDG_STATE_HOME=" + fixture.Data] );
            Equal( 0, shared.ExitCode );
            True( seeded.Kept.Concat( foreign ).All( File.Exists ), "state and unlisted files in the program folder are kept" );
            True( seeded.Removed.All( file => !File.Exists( file ) ), "the listed files are removed" );
            True( shared.StandardOutput.Contains( "Kept " + seeded.Program, StringComparison.Ordinal ), shared.StandardOutput );

            // A linked picker folder is not the installer's: nothing listed in
            // picker/ is removed through it.
            fixture = await CreateDownloadFixtureAsync( Directory.CreateDirectory( Path.Combine( root, "linked-picker" ) ).FullName );
            seeded = await SeedInstallationAsync( fixture, fixture.State );
            var elsewhere = Path.Combine( fixture.Root, "my-picker" );
            Directory.Move( Path.Combine( seeded.Program, "picker" ), elsewhere );
            File.CreateSymbolicLink( Path.Combine( seeded.Program, "picker" ), elsewhere );
            var linked = await RunDownloaderAsync( fixture, ["--uninstall"], "x86_64", "ok" );
            Equal( 0, linked.ExitCode );
            True( File.Exists( Path.Combine( elsewhere, "shell.qml" ) ), "a file in the linked picker folder stays" );
            True( !File.Exists( seeded.Binary ), "the binary is removed" );

            // An installation from before the list: exactly the files those
            // releases shipped go, and an unlisted library stays.
            fixture = await CreateDownloadFixtureAsync( Directory.CreateDirectory( Path.Combine( root, "legacy" ) ).FullName );
            seeded = await SeedInstallationAsync( fixture, fixture.State, withList: false );
            var custom = Path.Combine( seeded.Program, "custom.so" );
            await File.WriteAllTextAsync( custom, "mine" );
            var legacy = await RunDownloaderAsync( fixture, ["--uninstall"], "x86_64", "ok" );
            Equal( 0, legacy.ExitCode );
            True( seeded.Removed.All( file => !File.Exists( file ) ), "the files of the earlier releases are removed" );
            True( File.Exists( custom ), "an unlisted library stays" );
        }
        finally
        {
            Directory.Delete( root, recursive: true );
        }
    }

    // install-local.sh lists the files it installs. An update removes the
    // listed files that the new build no longer has and keeps files that no
    // list names. Over an install from before the list, it treats the files of
    // those releases as listed, and install-release.sh has the same list.
    private static async Task InstallLocalListsItsFilesAndPrunesOnlyThoseAsync( )
    {
        if ( !OperatingSystem.IsLinux( ) )
        {
            throw new SpecSkippedException( "This fixture requires Linux." );
        }

        var root = SpecTemporaryFiles.CreateDirectory( "commanddeck-install-local-" ).FullName;

        try
        {
            var home = Directory.CreateDirectory( Path.Combine( root, "home" ) ).FullName;
            var program = Path.Combine( home, ".local", "share", "commanddeck" );
            foreach ( var (build, files) in new[] { ("v1", "extra.so picker/old.qml"), ("v2", "") } )
            {
                var folder = Directory.CreateDirectory( Path.Combine( root, build, "picker" ) ).Parent!.FullName;
                await WriteExecutableAsync( Path.Combine( folder, "commanddeck" ), "#!/bin/sh\n" );
                foreach ( var file in ("libe_sqlite3.so picker/shell.qml " + files).Split( ' ', StringSplitOptions.RemoveEmptyEntries ) )
                {
                    await File.WriteAllTextAsync( Path.Combine( folder, file ), build );
                }
            }

            string[] legacy = [Path.Combine( program, "commanddeck" ), Path.Combine( program, "commanddeck.schema.json" ),
                Path.Combine( program, "picker", "TabFence.js" )];
            var mine = Path.Combine( program, "picker", "mine.qml" );
            foreach ( var file in legacy.Append( mine ) )
            {
                Directory.CreateDirectory( Path.GetDirectoryName( file )! );
                await File.WriteAllTextAsync( file, "earlier release" );
            }

            Equal( 0, (await RunInstallLocalAsync( root, home, "v1" )).ExitCode );
            True( legacy.Skip( 1 ).All( file => !File.Exists( file ) ), "the earlier release's files that v1 dropped are removed" );
            True( File.Exists( mine ), "a file that the earlier release did not ship stays" );

            var scripts = Path.Combine( FindRepositoryRoot( ), "scripts" );
            var local = LegacyListPattern( ).Match( await File.ReadAllTextAsync( Path.Combine( scripts, "install-local.sh" ) ) );
            var release = LegacyListPattern( ).Match( await File.ReadAllTextAsync( Path.Combine( scripts, "install-release.sh" ) ) );
            True( local.Success && release.Success, "both scripts have the legacy list" );
            Equal( local.Groups["list"].Value, release.Groups["list"].Value );

            string[] foreign = [Path.Combine( program, "custom.so" ), Path.Combine( program, "picker", "notes.txt" )];
            foreach ( var file in foreign )
            {
                await File.WriteAllTextAsync( file, "mine" );
            }

            Equal( 0, (await RunInstallLocalAsync( root, home, "v2" )).ExitCode );
            True( !File.Exists( Path.Combine( program, "extra.so" ) ) && !File.Exists( Path.Combine( program, "picker", "old.qml" ) ),
                "an update removes the listed files that the new build dropped" );
            True( foreign.All( File.Exists ), "an update keeps files that no list names" );
            Equal( "commanddeck\nlibe_sqlite3.so\npicker/shell.qml\n", await File.ReadAllTextAsync( Path.Combine( program, ".installed-files" ) ) );
        }
        finally
        {
            Directory.Delete( root, recursive: true );
        }
    }

    [System.Text.RegularExpressions.GeneratedRegex( "legacy_(?:entries|program_files)='(?<list>[^']*)'" )]
    private static partial System.Text.RegularExpressions.Regex LegacyListPattern( );

    private static async Task<ProcessResult> RunInstallLocalAsync( string root, string home, string build )
    {
        string[] arguments =
        [
            "HOME=" + home, "XDG_DATA_HOME=" + Path.Combine( home, ".local", "share" ), "bash",
            Path.Combine( FindRepositoryRoot( ), "scripts", "install-local.sh" ), Path.Combine( root, build )
        ];

        return await ProcessRunner.RunAsync( "env", arguments, null, root, TimeSpan.FromSeconds( 30 ), default );
    }

    private sealed record SeededInstallation( string Program, string Binary, string Link, string Hypr, string Plugin, string Service,
        string[] Removed, string[] Kept );

    // Lays out what install.sh leaves behind, plus files it does not own.
    // stateHome is the XDG state folder, so a case can share it with the
    // program folder. The binary is "working", "missing", or "broken" (it
    // exists but cannot run). With withList, install-local.sh's list of the
    // files it installed is there too, and it names a library that releases
    // before the list did not ship.
    [System.Runtime.Versioning.SupportedOSPlatform( "linux" )]
    private static async Task<SeededInstallation> SeedInstallationAsync( DownloadFixture fixture, string stateHome, string binaryKind = "working",
        bool withList = true )
    {
        var program = Directory.CreateDirectory( Path.Combine( fixture.Data, "commanddeck" ) ).FullName;
        var binary = Path.Combine( program, "commanddeck" );
        var hypr = Directory.CreateDirectory( Path.Combine( fixture.Config, "hypr" ) ).FullName;
        if ( binaryKind == "broken" )
        {
            await WriteExecutableAsync( binary, "#!/bin/sh\necho 'cannot load libicuuc' >&2\nexit 127\n" );
        }
        else if ( binaryKind == "working" )
        {
            await WriteExecutableAsync( binary, $$"""
                #!/bin/sh
                case "$1" in
                  version) echo 'commanddeck 9.9.9+0123abc' ;;
                  *) echo "commanddeck $*" >>"$COMMANDDECK_SPEC_INSTALL_CALLS.tools"; rm -f "{{hypr}}/commanddeck.lua" ;;
                esac
                """ );
        }

        var link = Path.Combine( fixture.Home, ".local", "bin", "commanddeck" );
        Directory.CreateDirectory( Path.GetDirectoryName( link )! );
        File.CreateSymbolicLink( link, binary );

        var plugin = Path.Combine( fixture.Config, "omarchy", "plugins", "local.commanddeck" );
        var service = Path.Combine( fixture.Config, "systemd", "user", "commanddeck.service" );
        List<(string Path, string Content)> removed =
        [
            (Path.Combine( program, "commanddeck.schema.json" ), "{}"), (Path.Combine( program, "libe_sqlite3.so" ), "x"),
            (Path.Combine( program, "picker", "shell.qml" ), "x"), (service, "x"), (Path.Combine( plugin, "manifest.json" ), "{}"),
            (Path.Combine( hypr, "commanddeck.lua" ), GeneratedHotkeyHeader),
            (Path.Combine( hypr, "commanddeck_keys.lua" ), GeneratedKeysHeader),
            (Path.Combine( hypr, "commanddeck_keys.lua.bak" ), GeneratedKeysHeader)
        ];
        if ( withList )
        {
            removed.Add( (Path.Combine( program, "libnew.so" ), "x") );
            removed.Add( (Path.Combine( program, ".installed-files" ),
                "commanddeck\ncommanddeck.schema.json\nlibe_sqlite3.so\nlibnew.so\npicker/shell.qml\n") );
        }

        (string Path, string Content)[] kept =
        [
            (Path.Combine( fixture.Config, "commanddeck", "commanddeck.jsonc" ), "{}"),
            (Path.Combine( stateHome, "commanddeck", "catalog.db" ), "x"),
            (Path.Combine( hypr, "hyprland.lua" ), "-- mine\n"),
            (Path.Combine( hypr, "commanddeck.lua.bak" ), "-- my own copy\n")
        ];
        foreach ( var (path, content) in removed.Concat( kept ) )
        {
            Directory.CreateDirectory( Path.GetDirectoryName( path )! );
            await File.WriteAllTextAsync( path, content );
        }

        string[] removedPaths = [.. removed.Select( file => file.Path ), .. binaryKind == "missing" ? Array.Empty<string>( ) : new[] { binary }];

        return new SeededInstallation( program, binary, link, hypr, plugin, service, removedPaths, [.. kept.Select( file => file.Path )] );
    }
