    private const string StockHyprlandLua = """
                                            dofile((os.getenv("OMARCHY_PATH") or "/usr/share/omarchy") .. "/default/hypr/bootstrap.lua")
                                            require("default.hypr.omarchy")
                                            require("hypr.monitors")
                                            require("hypr.input")
                                            require("hypr.bindings")
                                            require("hypr.looknfeel")
                                            require("hypr.autostart")
                                            require("default.hypr.toggles")

                                            """;

    private const string StockBindingsLua = """
                                            -- Keep only your personal keybinding overrides here.
                                            -- o.bind("SUPER + PERIOD", nil, "omarchy-shell shell toggle omarchy.emojis")
                                            o.bind("SUPER + SHIFT + R", "SSH", "alacritty -e ssh example")

                                            """;

    // Exactly what the earlier reinstall script appended to bindings.lua.
    private const string LegacyBindingBlock = """

                                              -- BEGIN COMMANDDECK CTRL SPACE
                                              hl.unbind("CTRL + SPACE")
                                              hl.bind(
                                                "CTRL + SPACE",
                                                hl.dsp.exec_cmd([[omarchy-shell shell toggle local.commanddeck '{}']]),
                                                { description = "CommandDeck" }
                                              )
                                              -- END COMMANDDECK CTRL SPACE

                                              """;

    private const string ExpectedRequireLine =
        """if package.searchpath("hypr.commanddeck", package.path) then require("hypr.commanddeck") end -- CommandDeck hotkey""";

    private static readonly DateTimeOffset HotkeyClock = new( 2026, 10, 20, 9, 30, 0,
        TimeSpan.Zero );

    private static void HotkeyInstallWritesItsOwnModuleAndOneRequire( )
    {
        using HotkeyFixture fixture = new( );
        var dotfile = Path.Combine( fixture.Root, "dotfiles", "hyprland.lua" );
        Directory.CreateDirectory( Path.GetDirectoryName( dotfile )! );
        File.WriteAllText( dotfile, StockHyprlandLua );
        File.CreateSymbolicLink( fixture.Paths.MainConfig, dotfile );
        File.WriteAllText( fixture.Paths.Bindings, StockBindingsLua );
        var messages = fixture.Installer.Install( "CTRL + SPACE" );

        Equal( """
               -- Generated by `commanddeck hotkey install`.
               -- Changes here are overwritten. Run `commanddeck hotkey install --chord CHORD`
               -- to change the key, or `commanddeck hotkey remove` to delete this file.
               -- The chord reaches the CommandDeck shell plugin as a Hyprland global
               -- shortcut, so the launcher opens without starting a process.
               hl.unbind("CTRL + SPACE")
               hl.bind("CTRL + SPACE", hl.dsp.global("commanddeck:toggle"), { description = "CommandDeck" })

               """, File.ReadAllText( Path.Combine( fixture.Paths.HyprDirectory, "commanddeck.lua" ) ) );

        Equal(
            StockHyprlandLua.Replace( "require(\"hypr.bindings\")\n", "require(\"hypr.bindings\")\n" + ExpectedRequireLine + "\n", StringComparison.Ordinal ),
            File.ReadAllText( dotfile ) );

        True( File.ResolveLinkTarget( fixture.Paths.MainConfig, returnFinalTarget: false ) is not null, "the symlinked hyprland.lua stays a symlink" );

        Equal( StockBindingsLua, File.ReadAllText( fixture.Paths.Bindings ) );
        Equal( StockHyprlandLua, File.ReadAllText( fixture.Backup( "hyprland.lua" ) ) );
        Equal( 1, fixture.Backups( ).Length );

        True( messages.Any( static message => message.Contains( "commanddeck:toggle", StringComparison.Ordinal ) ) );
    }

    private static void HotkeyInstallIsIdempotent( )
    {
        using HotkeyFixture fixture = new( );
        File.WriteAllText( fixture.Paths.MainConfig, StockHyprlandLua );
        fixture.Installer.Install( "CTRL + SPACE" );
        var module = File.ReadAllText( fixture.Paths.HotkeyFile );
        var main = File.ReadAllText( fixture.Paths.MainConfig );
        var moduleWritten = File.GetLastWriteTimeUtc( fixture.Paths.HotkeyFile );
        var rerun = fixture.Installer.Install( "ctrl+space" );
        Equal( module, File.ReadAllText( fixture.Paths.HotkeyFile ) );
        Equal( main, File.ReadAllText( fixture.Paths.MainConfig ) );
        Equal( moduleWritten, File.GetLastWriteTimeUtc( fixture.Paths.HotkeyFile ) );
        Equal( 1, fixture.Backups( ).Length );
        Equal( "The CTRL + SPACE CommandDeck hotkey is already installed.", rerun.Single( ) );
        File.WriteAllText( fixture.Paths.MainConfig, main + "require(\"hypr.commanddeck\")\n" );
        fixture.Installer.Install( "CTRL + SPACE" );
        Equal( main, File.ReadAllText( fixture.Paths.MainConfig ) );

        Equal( 1, File
            .ReadAllLines( fixture.Paths.MainConfig )
            .Count( static line => line.Contains( "hypr.commanddeck", StringComparison.Ordinal ) ) );
    }

    private static void HotkeyInstallMigratesTheEarlierBindingsBlock( )
    {
        using HotkeyFixture fixture = new( );
        File.WriteAllText( fixture.Paths.MainConfig, StockHyprlandLua );
        var userAfter = "o.bind(\"SUPER + J\", \"Journal\", \"journal\")\n";
        var legacy = StockBindingsLua + LegacyBindingBlock + userAfter;
        File.WriteAllText( fixture.Paths.Bindings, legacy );
        var messages = fixture.Installer.Install( "CTRL + SPACE" );
        Equal( StockBindingsLua + userAfter, File.ReadAllText( fixture.Paths.Bindings ) );
        Equal( legacy, File.ReadAllText( fixture.Backup( "bindings.lua" ) ) );

        True( File
            .ReadAllText( fixture.Paths.HotkeyFile )
            .Contains( "hl.dsp.global(\"commanddeck:toggle\")", StringComparison.Ordinal ) );

        Equal( 1, HyprlandHotkeyConfig.CountRequires( File.ReadAllText( fixture.Paths.MainConfig ) ) );

        True( messages.Any( static message => message.Contains( "earlier CommandDeck block", StringComparison.Ordinal ) ) );

        True( !File
            .ReadAllText( fixture.Paths.Bindings )
            .Contains( "local.commanddeck", StringComparison.Ordinal ) );

        File.WriteAllText( fixture.Paths.Bindings, "-- BEGIN COMMANDDECK CTRL SPACE\nhl.unbind(\"CTRL + SPACE\")\n" );

        Throws<InvalidOperationException>( ( ) => fixture.Installer.Install( "CTRL + SPACE" ) );
    }

    private static void HotkeyInstallBindsACustomChord( )
    {
        using HotkeyFixture fixture = new( );
        File.WriteAllText( fixture.Paths.MainConfig, StockHyprlandLua );
        fixture.Installer.Install( "super + shift + k" );
        var custom = File.ReadAllText( fixture.Paths.HotkeyFile );
        True( custom.Contains( "hl.unbind(\"SUPER + SHIFT + K\")\n", StringComparison.Ordinal ) );
        True( custom.Contains( "hl.bind(\"SUPER + SHIFT + K\", hl.dsp.global(\"commanddeck:toggle\")", StringComparison.Ordinal ) );

        Equal( "SUPER + SHIFT + K", HyprlandHotkeyConfig.ReadChord( custom ) );
        fixture.Installer.Install( "ALT + XF86Launch5" );

        Equal( "ALT + XF86Launch5", HyprlandHotkeyConfig.ReadChord( File.ReadAllText( fixture.Paths.HotkeyFile ) ) );
        Equal( 1, HyprlandHotkeyConfig.CountRequires( File.ReadAllText( fixture.Paths.MainConfig ) ) );

        foreach ( var invalid in new[] { "", "CTRL +", "HYPER + K", "CTRL + CTRL + K", "CTRL + SPACE\")", "CTRL + a b" } )
        {
            Throws<InvalidOperationException>( ( ) => fixture.Installer.Install( invalid ) );
        }

        Equal( "ALT + XF86Launch5", HyprlandHotkeyConfig.ReadChord( File.ReadAllText( fixture.Paths.HotkeyFile ) ) );
    }

    private static void HotkeyRemoveDeletesTheModuleAndRequire( )
    {
        using HotkeyFixture fixture = new( );
        File.WriteAllText( fixture.Paths.MainConfig, StockHyprlandLua );
        File.WriteAllText( fixture.Paths.Bindings, StockBindingsLua + LegacyBindingBlock );
        fixture.Installer.Install( "CTRL + SPACE" );
        File.AppendAllText( fixture.Paths.Bindings, LegacyBindingBlock );
        var removed = fixture.Installer.Remove( );
        Equal( StockHyprlandLua, File.ReadAllText( fixture.Paths.MainConfig ) );
        Equal( StockBindingsLua, File.ReadAllText( fixture.Paths.Bindings ) );
        True( !File.Exists( fixture.Paths.HotkeyFile ) );
        True( removed.Any( static message => message.Contains( "Deleted", StringComparison.Ordinal ) ) );

        Equal( "No CommandDeck hotkey is installed.", fixture
            .Installer.Remove( )
            .Single( ) );

        File.WriteAllText( fixture.Paths.HotkeyFile, "-- my own module\n" );
        fixture.Installer.Remove( );
        Equal( "-- my own module\n", File.ReadAllText( fixture.Paths.HotkeyFile ) );
    }

    private static void HotkeyInstallKeepsTheExistingConflictChecks( )
    {
        using HotkeyFixture fixture = new( );
        File.WriteAllText( fixture.Paths.MainConfig, StockHyprlandLua );

        var userBinding = StockBindingsLua +
                          """
                          hl.bind(
                            "CTRL+SPACE",
                            hl.dsp.exec_cmd("omarchy-shell shell toggle local.commanddeck '{}'")
                          )

                          """;

        File.WriteAllText( fixture.Paths.Bindings, userBinding );
        var kept = fixture.Installer.Install( "CTRL + SPACE" );
        Equal( StockHyprlandLua, File.ReadAllText( fixture.Paths.MainConfig ) );
        True( !File.Exists( fixture.Paths.HotkeyFile ) );

        True( kept
            .Single( )
            .Contains( "leaving your binding", StringComparison.Ordinal ) );

        File.WriteAllText( fixture.Paths.Bindings,
            StockBindingsLua +
            "o.bind(\"CTRL + SPACE\", \"Other\", \"other-launcher\")\n" +
            "o.bind(\"SUPER + CTRL + SPACE\", \"Background\", \"local.commanddeck\")\n" );

        var replaced = fixture.Installer.Install( "CTRL + SPACE" );
        True( File.Exists( fixture.Paths.HotkeyFile ) );
        True( replaced.Any( static message => message.StartsWith( "Note:", StringComparison.Ordinal ) ) );
        True( !HyprlandHotkeyConfig.HasUserBinding( "o.bind(\"SUPER + CTRL + SPACE\", nil, \"local.commanddeck\")", "CTRL + SPACE" ) );
        True( HyprlandHotkeyConfig.HasUserBinding( "o.bind(\"CTRL + SUPER + K\", nil, \"local.commanddeck\")", "SUPER + CTRL + K" ) );
    }

    private static void HotkeyInstallRequiresOmarchyLuaConfiguration( )
    {
        using HotkeyFixture fixture = new( );
        Throws<InvalidOperationException>( ( ) => fixture.Installer.Install( "CTRL + SPACE" ) );
        True( !File.Exists( fixture.Paths.HotkeyFile ) );
        True( !File.Exists( fixture.Paths.MainConfig ) );
    }
