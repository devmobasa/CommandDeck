    private static void HotkeyInstallBindsACustomChord( )
    {
        using HotkeyFixture fixture = new( );
        File.WriteAllText( fixture.Paths.MainConfig, StockHyprlandLua );
        fixture.Installer.Install( "super + shift + k" );
