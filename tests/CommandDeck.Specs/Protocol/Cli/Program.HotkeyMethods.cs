        Equal( "ALT + XF86Launch5", HyprlandHotkeyConfig.ReadChord( File.ReadAllText( fixture.Paths.HotkeyFile ) ) );
        Equal( 1, HyprlandHotkeyConfig.CountRequires( File.ReadAllText( fixture.Paths.MainConfig ) ) );

        foreach ( var invalid in new[] { "", "CTRL +", "HYPER + K", "CTRL + CTRL + K", "CTRL + SPACE\")", "CTRL + a b" } )
        {
            Throws<InvalidOperationException>( ( ) => fixture.Installer.Install( invalid ) );
        }

        Equal( "ALT + XF86Launch5", HyprlandHotkeyConfig.ReadChord( File.ReadAllText( fixture.Paths.HotkeyFile ) ) );
    }

    private static void HotkeyRemoveDeletesTheModuleAndRequire( )
    {
        using HotkeyFixture fixture = new( );
