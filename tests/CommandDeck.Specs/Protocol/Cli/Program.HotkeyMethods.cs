        True( custom.Contains( "hl.unbind(\"SUPER + SHIFT + K\")\n", StringComparison.Ordinal ) );
        True( custom.Contains( "hl.bind(\"SUPER + SHIFT + K\", hl.dsp.global(\"commanddeck:toggle\")", StringComparison.Ordinal ) );

        Equal( "SUPER + SHIFT + K", HyprlandHotkeyConfig.ReadChord( custom ) );
