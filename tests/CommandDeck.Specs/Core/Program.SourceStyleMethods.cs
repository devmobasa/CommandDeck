using System.Text;
using System.Text.RegularExpressions;

namespace CommandDeck.Specs;

public static partial class Program
{
    private static readonly string[] SourceDirectories = ["src", "tests", "scripts", "samples", "qml"];

    private static void HandwrittenCSharpLinesStayWithinLimit( )
    {
        var root = FindRepositoryRoot( );
        List<string> failures = [];
        foreach ( var path in RepositorySourceFiles( root, "*.cs" ).Where( IsHandwrittenCSharp ) )
        {
            var source = RemoveRawStringContents( File.ReadAllText( path ) );
            var lines = source.Split( '\n' );
            for ( var index = 0; index < lines.Length; index++ )
            {
                if ( lines[index].TrimEnd( '\r' ).Length > 160 )
                {
                    failures.Add( $"{Path.GetRelativePath( root, path )}:{index + 1}" );
                }
            }
        }

        True( failures.Count == 0, "Handwritten C# lines exceed 160 characters: " + string.Join( ", ", failures ) );
    }

    private static void SourceDirectoriesContainNoPython( )
    {
        var root = FindRepositoryRoot( );
        var paths = RepositorySourceFiles( root, "*.py" ).Select( path => Path.GetRelativePath( root, path ) );

        Equal( "", string.Join( ", ", paths ) );
    }

    private static IEnumerable<string> RepositorySourceFiles( string root, string pattern )
    {
        return SourceDirectories
            .Select( directory => Path.Combine( root, directory ) )
            .Where( Directory.Exists )
            .SelectMany( directory => Directory.EnumerateFiles( directory, pattern, SearchOption.AllDirectories ) )
            .Where( path => !path.Split( Path.DirectorySeparatorChar ).Any( part => part is "bin" or "obj" or ".git" ) );
    }

    private static bool IsHandwrittenCSharp( string path )
    {
        var name = Path.GetFileName( path );
        if ( name.EndsWith( ".g.cs", StringComparison.OrdinalIgnoreCase ) || name.EndsWith( ".generated.cs", StringComparison.OrdinalIgnoreCase ) )
        {
            return false;
        }

        var header = string.Join( '\n', File.ReadLines( path ).Take( 3 ) );

        return !header.Contains( "<auto-generated", StringComparison.OrdinalIgnoreCase ) &&
               !(header.Contains( "generated", StringComparison.OrdinalIgnoreCase ) && header.Contains( "do not edit", StringComparison.OrdinalIgnoreCase ));
    }

    // Consume comments and ordinary strings before recognizing raw delimiters.
    // Quotes inside an escaped string, a regex, or a comment are not delimiters.
    private static string RemoveRawStringContents( string source )
    {
        StringBuilder result = new( source.Length );
        var position = 0;
        foreach ( Match match in CSharpStyleTokens( ).Matches( source ) )
        {
            if ( match.Index < position )
            {
                continue;
            }

            result.Append( source, position, match.Index - position );
            var token = match.Value;
            if ( token[0] != '"' || token.Length < 3 || token.Any( character => character != '"' ) )
            {
                result.Append( token );
                position = match.Index + match.Length;
                continue;
            }

            var end = source.IndexOf( token, match.Index + match.Length, StringComparison.Ordinal );
            if ( end < 0 )
            {
                throw new InvalidOperationException( "Unterminated C# raw string in source style check." );
            }

            result.Append( token );
            foreach ( var character in source.AsSpan( match.Index + match.Length, end - match.Index - match.Length ) )
            {
                if ( character is '\n' or '\r' )
                {
                    result.Append( character );
                }
            }

            result.Append( token );
            position = end + token.Length;
        }

        result.Append( source, position, source.Length - position );

        return result.ToString( );
    }

    [GeneratedRegex( "//[^\\r\\n]*|/\\*[\\s\\S]*?\\*/|@\"(?:\"\"|[^\"])*\"|'(?:\\\\.|[^'\\\\])*'|\"{3,}|\"(?:\\\\.|[^\"\\\\])*\"" )]
    private static partial Regex CSharpStyleTokens( );
}
