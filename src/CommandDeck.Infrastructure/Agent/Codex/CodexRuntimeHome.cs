using System.Text;

namespace CommandDeck;

public sealed class CodexRuntimeHome : IDisposable
{
    private bool _disposed;

    private CodexRuntimeHome( string path, string generation, int trustLevel )
    {
        Path = path;
        Generation = generation;
        TrustLevel = trustLevel;
    }

    public string Path { get; }

    public string Generation { get; }

    public int TrustLevel { get; }

    public string AuthPath => System.IO.Path.Combine( Path, CodexCredentialStore.AuthFileName );

    public string SocketPath => System.IO.Path.Combine( Path, "app-server.sock" );

    public static CodexRuntimeHome Create( string runtimeDirectoryRoot, int trustLevel, bool webSearch )
    {
        var root = System.IO.Path.Combine( PathExpansion.Expand( runtimeDirectoryRoot ), "codex" );
        Directory.CreateDirectory( root );

        if ( OperatingSystem.IsLinux( ) )
        {
            File.SetUnixFileMode( root, UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute );
        }

        var generation = Guid
            .NewGuid( )
            .ToString( "N" );

        var path = System.IO.Path.Combine( root, generation );
        Directory.CreateDirectory( path );

        if ( OperatingSystem.IsLinux( ) )
        {
            File.SetUnixFileMode( path, UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute );
        }

        CodexRuntimeHome home = new( path, generation, trustLevel );
        home.WriteConfiguration( webSearch );

        return home;
    }

    public static string BuildConfiguration( int trustLevel, bool webSearch )
    {
        StringBuilder builder = new( );
        builder.Append( "# Generated by CommandDeck for one isolated App Server generation.\n" );
        builder.Append( "model_reasoning_summary = \"auto\"\n" );
        var allowWebSearch = webSearch && trustLevel >= AgentTrustLevels.Unrestricted;

        builder
            .Append( "web_search = \"" )
            .Append( allowWebSearch ? "live" : "disabled" )
            .Append( "\"\n" );

        builder.Append( "[history]\npersistence = \"none\"\n" );
        builder.Append( "[analytics]\nenabled = false\n" );

        if ( trustLevel < AgentTrustLevels.Unrestricted )
        {
            builder.Append( "[features]\n" );

            foreach ( var feature in DisabledFeaturesBelowUnrestricted )
            {
                builder
                    .Append( feature )
                    .Append( " = false\n" );
            }
        }

        return builder.ToString( );
    }

    public static IReadOnlyList<string> DisabledFeaturesBelowUnrestricted { get; } =
    [
        "shell_tool",
        "unified_exec",
        "browser_use",
        "computer_use",
        "apps",
        "plugins",
        "hooks",
        "memories",
        "multi_agent",
        "image_generation",
        "skill_search",
        "tool_suggest",
        "sleep_tool",
        "view_image",
        "goals",

        // "code_mode_host" is intentionally NOT disabled: the gpt-5.6-* models
        // invoke dynamic tools through Code Mode, and each such call still
        // returns to the client as a mediated item/tool/call (verified live).
        // The host runs inside the same locked sandbox (tmpfs home, read-only
        // system), and the generated code's only side effects are the mediated
        // CommandDeck tools. Disabling it makes those models' tools fail closed.
        "in_app_local_automation",
        "guardian_approval",
        "remote_control"
    ];

    public void ImportCredential( byte[]? json )
    {
        if ( json is null )
        {
            return;
        }

        using var stream = SafeRegularFile.CreatePrivateWriteStream( AuthPath );
        stream.Write( json );
        stream.Flush( flushToDisk: true );
    }

    public byte[]? ExportCredential( )
    {
        if ( !File.Exists( AuthPath ) )
        {
            return null;
        }

        try
        {
            using var file = SafeRegularFile.OpenFromDirectory( Path, CodexCredentialStore.AuthFileName );
            if ( file.Length is 0 or > CodexCredentialStore.MaximumBytes )
            {
                return null;
            }

            var buffer = new byte[file.Length];
            var total = 0;
            while ( total < buffer.Length )
            {
                var read = RandomAccess.Read( file.Handle, buffer.AsSpan( total ), total );
                if ( read <= 0 )
                {
                    break;
                }

                total += read;
            }

            if ( HasValidCredentialBuffer( buffer, total ) )
            {
                return buffer;
            }

            CodexCredentialStore.Clear( buffer );

            return null;
        }
        catch ( InvalidOperationException )
        {
            return null;
        }
    }

    public void Wipe( )
    {
        try
        {
            if ( Directory.Exists( Path ) )
            {
                Directory.Delete( Path, recursive: true );
            }
        }
        catch ( IOException )
        {
        }
        catch ( UnauthorizedAccessException )
        {
        }
    }

    private void WriteConfiguration( bool webSearch )
    {
        var configuration = BuildConfiguration( TrustLevel, webSearch );

        using var stream = SafeRegularFile.CreatePrivateWriteStream( System.IO.Path.Combine( Path, "config.toml" ) );

        stream.Write( Encoding.UTF8.GetBytes( configuration ) );
        stream.Flush( flushToDisk: true );
    }

    public void Dispose( )
    {
        if ( _disposed )
        {
            return;
        }

        _disposed = true;
        Wipe( );
    }

    private static bool HasValidCredentialBuffer( byte[] buffer, int total )
    {
        return total == buffer.Length && CodexCredentialStore.IsValidCredentialJson( buffer );
    }
}
