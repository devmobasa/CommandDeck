using System.Text;
using System.Text.RegularExpressions;

namespace CommandDeck;

// The Hyprland Lua that sends the launcher chord to the Omarchy plugin's global
// shortcut, as text transformations only. HyprlandHotkeyInstaller owns the files.
public static partial class HyprlandHotkeyConfig
{
    private const string ChordName = "chord";

    public const string ShortcutAppId = "commanddeck";
    public const string ShortcutName = "toggle";
    public const string ShortcutId = ShortcutAppId + ":" + ShortcutName;
    public const string BindingDescription = "CommandDeck";
    public const string DefaultChord = "CTRL + SPACE";
    public const string ModuleName = "hypr.commanddeck";
    public const string FileName = "commanddeck.lua";

    public const string GeneratedHeader = "-- Generated by `commanddeck hotkey install`.";

    // Guarded so a deleted module file cannot stop the rest of hyprland.lua.
    public const string RequireLine =
        "if package.searchpath(\"" + ModuleName + "\", package.path) then require(\"" + ModuleName + "\") end -- CommandDeck hotkey";

    internal const string LegacyBlockBegin = "-- BEGIN COMMANDDECK CTRL SPACE";
    internal const string LegacyBlockEnd = "-- END COMMANDDECK CTRL SPACE";

    private const int MaximumChordCharacters = 64;

    // Lines the earlier installer's check scanned after a chord for a CommandDeck target.
    private const int UserBindingWindowLines = 6;

    private static readonly Dictionary<string, string> Modifiers = new( StringComparer.OrdinalIgnoreCase )
    {
        [ShortcutModifiers.Super] = ShortcutModifiers.Super,
        ["WIN"] = ShortcutModifiers.Super,
        ["LOGO"] = ShortcutModifiers.Super,
        ["MOD4"] = ShortcutModifiers.Super,
        [ShortcutModifiers.Control] = ShortcutModifiers.Control,
        ["CONTROL"] = ShortcutModifiers.Control,
        [ShortcutModifiers.Alt] = ShortcutModifiers.Alt,
        ["MOD1"] = ShortcutModifiers.Alt,
        [ShortcutModifiers.Shift] = ShortcutModifiers.Shift,
        ["MOD2"] = "MOD2",
        ["MOD3"] = "MOD3",
        ["MOD5"] = "MOD5"
    };

    // Accepts "ctrl+space" or "Super + Shift + K" and returns Omarchy's
    // "CTRL + SPACE" form. A mixed-case key name such as XF86AudioMute keeps its case.
    public static string NormalizeChord( string chord )
    {
        if ( IsInvalidChord( chord ) )
        {
            throw new InvalidOperationException( $"A hotkey chord is one to {MaximumChordCharacters} characters, such as \"{DefaultChord}\"." );
        }

        var parts = chord.Split( '+', StringSplitOptions.TrimEntries );
        if ( parts.Any( static part => part.Length == 0 ) )
        {
            throw new InvalidOperationException( $"\"{chord}\" has an empty part; write modifiers and a key, such as \"{DefaultChord}\"." );
        }

        List<string> normalized = [];
        foreach ( var modifier in parts[..^1] )
        {
            if ( !Modifiers.TryGetValue( modifier, out var name ) )
            {
                throw new InvalidOperationException( $"\"{modifier}\" is not a Hyprland modifier (SUPER, CTRL, ALT, SHIFT)." );
            }

            if ( normalized.Contains( name, StringComparer.Ordinal ) )
            {
                throw new InvalidOperationException( $"\"{chord}\" repeats the {name} modifier." );
            }

            normalized.Add( name );
        }

        normalized.Add( NormalizeKey( parts[^1], chord ) );

        return string.Join( " + ", normalized );
    }

    public static string GenerateFile( string chord )
    {
        var normalized = NormalizeChord( chord );
        StringBuilder text = new( );

        text
            .Append( GeneratedHeader )
            .Append( '\n' );

        text.Append( "-- Changes here are overwritten. Run `commanddeck hotkey install --chord CHORD`\n" );
        text.Append( "-- to change the key, or `commanddeck hotkey remove` to delete this file.\n" );
        text.Append( "-- The chord reaches the CommandDeck shell plugin as a Hyprland global\n" );
        text.Append( "-- shortcut, so the launcher opens without starting a process.\n" );

        text
            .Append( "hl.unbind(\"" )
            .Append( normalized )
            .Append( "\")\n" );

        text
            .Append( "hl.bind(\"" )
            .Append( normalized )
            .Append( "\", hl.dsp.global(\"" )
            .Append( ShortcutId )
            .Append( "\"), { description = \"" )
            .Append( BindingDescription )
            .Append( "\" })\n" );

        return text.ToString( );
    }

    public static bool IsGenerated( string content ) => content.StartsWith( GeneratedHeader, StringComparison.Ordinal );

    // The chord a generated file binds, or null when the file is not ours.
    public static string? ReadChord( string content )
    {
        if ( !IsGenerated( content ) )
        {
            return null;
        }

        var match = GeneratedBindPattern( )
            .Match( content );

        return match.Success ? match.Groups[ChordName].Value : null;
    }

    public static int CountRequires( string hyprlandLua ) => SplitLines( hyprlandLua )
        .Count( IsRequireLine );

    // Exactly one canonical require line. An existing canonical line keeps its
    // place; otherwise the line follows require("hypr.bindings"), so the
    // CommandDeck chord replaces a personal binding of the same keys, as the
    // earlier block at the end of bindings.lua did.
    public static string EnsureRequire( string hyprlandLua )
    {
        var lines = SplitLines( hyprlandLua );
        var canonical = lines.FindIndex( static line => line.TrimEnd( '\r' ) == RequireLine );
        if ( HasSingleCanonicalRequire( lines, canonical ) )
        {
            return hyprlandLua;
        }

        if ( canonical >= 0 )
        {
            var kept = KeepCanonicalRequire( lines, canonical );

            return JoinLines( kept, hyprlandLua );
        }

        var remaining = RemoveRequireLines( lines );

        var anchor = remaining.FindLastIndex( static line => BindingsRequirePattern( )
            .IsMatch( line ) );

        if ( anchor >= 0 )
        {
            remaining.Insert( anchor + 1, RequireLine );
        }
        else
        {
            while ( remaining.Count > 0 && remaining[^1].Length == 0 )
            {
                remaining.RemoveAt( remaining.Count - 1 );
            }

            if ( remaining.Count > 0 )
            {
                remaining.Add( string.Empty );
            }

            remaining.Add( RequireLine );
        }

        return JoinLines( remaining, hyprlandLua, forceTrailingNewline: true );
    }

    public static string RemoveRequire( string hyprlandLua )
    {
        var lines = SplitLines( hyprlandLua );
        if ( lines.Any( IsRequireLine ) )
        {
            return JoinLines( RemoveRequireLines( lines ), hyprlandLua );
        }
        else
        {
            return hyprlandLua;
        }
    }

    public static bool HasLegacyBlock( string bindingsLua ) => SplitLines( bindingsLua )
        .Any( static line => line.Trim( ) == LegacyBlockBegin );

    // Removes the block the earlier installer appended, with the blank line it
    // wrote before the block. An unterminated block is left for manual repair.
    public static string RemoveLegacyBlock( string bindingsLua )
    {
        var lines = SplitLines( bindingsLua );
        var begin = lines.FindIndex( static line => line.Trim( ) == LegacyBlockBegin );
        if ( begin < 0 )
        {
            return bindingsLua;
        }

        var end = lines.FindIndex( begin, static line => line.Trim( ) == LegacyBlockEnd );
        if ( end < 0 )
        {
            throw new InvalidOperationException(
                $"bindings.lua has \"{LegacyBlockBegin}\" without \"{LegacyBlockEnd}\"; remove the old CommandDeck lines by hand." );
        }

        var start = begin;
        if ( HasBlankLineBefore( lines, begin ) )
        {
            start = begin - 1;
        }

        lines.RemoveRange( start, end - start + 1 );

        return RemoveLegacyBlock( JoinLines( lines, bindingsLua ) );
    }

    // A binding the user wrote for this chord that already opens CommandDeck,
    // found the way the earlier installer's check did: a CommandDeck target
    // within a few lines after the chord, now ending at the next bind call.
    // Comment lines are ignored.
    public static bool HasUserBinding( string bindingsLua, string chord )
    {
        var pattern = ChordPattern( NormalizeChord( chord ) );
        var lines = GetNonCommentLines( bindingsLua );
        for ( var index = 0; index < lines.Count; index++ )
        {
            if ( !pattern.IsMatch( lines[index] ) )
            {
                continue;
            }

            var window = GetUserBindingWindow( lines, index );
            if ( window.Any( static line =>
                    line.Contains( CommandDeckIdentity.PluginId, StringComparison.Ordinal ) || line.Contains( ShortcutId, StringComparison.Ordinal ) ) )
            {
                return true;
            }
        }

        return false;
    }

    // Uncommented lines that name the chord, which the CommandDeck binding replaces.
    public static bool MentionsChord( string luaText, string chord )
    {
        var pattern = ChordPattern( NormalizeChord( chord ) );

        return SplitLines( luaText )
            .Any( line => !IsComment( line ) && pattern.IsMatch( line ) );
    }

    private static string NormalizeKey( string key, string chord )
    {
        if ( CodeKeyPattern( )
            .IsMatch( key ) )
        {
            return key.ToLowerInvariant( );
        }

        if ( !KeyPattern( )
                .IsMatch( key ) )
        {
            throw new InvalidOperationException( $"\"{chord}\" does not end with a key name such as SPACE, K, or F12." );
        }

        var mixedCase = HasMixedCase( key );

        return mixedCase ? key : key.ToUpperInvariant( );
    }

    // Matches the chord with its modifiers in any order, but not as part of a
    // longer chord: CTRL + SPACE does not match SUPER + CTRL + SPACE.
    private static Regex ChordPattern( string normalized )
    {
        var parts = normalized.Split( " + " );
        var orders = GetModifierOrderPatterns( parts );

        return new Regex( @"(?<![\w+]\s*)(?:" + string.Join( '|', orders ) + @")(?!\w|\s*\+)", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant );
    }

    private static IEnumerable<IEnumerable<string>> Permutations( string[] values )
    {
        if ( values.Length <= 1 )
        {
            yield return values;

            yield break;
        }

        for ( var index = 0; index < values.Length; index++ )
        {
            var rest = GetRemainingPermutationValues( values, index );
            foreach ( var order in Permutations( rest ) )
            {
                yield return order.Prepend( values[index] );
            }
        }
    }

    private static bool IsRequireLine( string line ) => !IsComment( line ) &&
                                                        (line.Contains( "\"" + ModuleName + "\"", StringComparison.Ordinal ) ||
                                                         line.Contains( "'" + ModuleName + "'", StringComparison.Ordinal ));

    private static bool IsComment( string line ) => line
        .TrimStart( )
        .StartsWith( "--", StringComparison.Ordinal );

    private static List<string> SplitLines( string text )
    {
        var lines = text
            .Split( '\n' )
            .ToList( );

        if ( lines.Count > 0 && lines[^1].Length == 0 )
        {
            lines.RemoveAt( lines.Count - 1 );
        }

        return lines;
    }

    private static string JoinLines( List<string> lines, string original, bool forceTrailingNewline = false )
    {
        var joined = string.Join( '\n', lines );

        return lines.Count > 0 && (forceTrailingNewline || original.EndsWith( '\n' )) ? joined + "\n" : joined;
    }

    [GeneratedRegex( """^hl\.bind\("(?<chord>[^"]+)", hl\.dsp\.global\("commanddeck:toggle"\)""", RegexOptions.Multiline )]
    private static partial Regex GeneratedBindPattern( );

    [GeneratedRegex( """^\s*require\s*\(?\s*["']hypr\.bindings["']""" )]
    private static partial Regex BindingsRequirePattern( );

    [GeneratedRegex( @"\b(?:hl\.bind|hl\.unbind|o\.bind\w*)\s*\(" )]
    private static partial Regex BindCallPattern( );

    [GeneratedRegex( "^[A-Za-z0-9_]{1,32}$" )]
    private static partial Regex KeyPattern( );

    [GeneratedRegex( "^code:[0-9]{1,4}$", RegexOptions.IgnoreCase )]
    private static partial Regex CodeKeyPattern( );

    private static bool IsInvalidChord( string chord )
    {
        return string.IsNullOrWhiteSpace( chord ) || chord.Length > MaximumChordCharacters;
    }

    private static bool HasSingleCanonicalRequire( List<string> lines, int canonical )
    {
        return canonical >= 0 && lines.Count( IsRequireLine ) == 1;
    }

    private static List<string> KeepCanonicalRequire( List<string> lines, int canonical )
    {
        return lines
            .Where( ( line, index ) => index == canonical || !IsRequireLine( line ) )
            .ToList( );
    }

    private static List<string> RemoveRequireLines( List<string> lines )
    {
        return lines
            .Where( static line => !IsRequireLine( line ) )
            .ToList( );
    }

    private static List<string> GetNonCommentLines( string bindingsLua )
    {
        return SplitLines( bindingsLua )
            .Where( static line => !IsComment( line ) )
            .ToList( );
    }

    private static IEnumerable<string> GetUserBindingWindow( List<string> lines, int index )
    {
        return lines
            .Skip( index )
            .Take( UserBindingWindowLines )
            .TakeWhile( ( line, offset ) => offset == 0 ||
                                            !BindCallPattern( )
                                                .IsMatch( line ) );
    }

    private static IEnumerable<string> GetModifierOrderPatterns( string[] parts )
    {
        return Permutations( parts[..^1] )
            .Select( order => string.Join( @"\s*\+\s*", order
                .Append( parts[^1] )
                .Select( Regex.Escape ) ) );
    }

    private static string[] GetRemainingPermutationValues( string[] values, int index )
    {
        return values
            .Where( ( _, position ) => position != index )
            .ToArray( );
    }

    private static bool HasBlankLineBefore( List<string> lines, int begin )
    {
        return begin > 0 &&
               lines[begin - 1]
                   .Trim( )
                   .Length ==
               0;
    }

    private static bool HasMixedCase( string key )
    {
        return key.Any( char.IsUpper ) && key.Any( char.IsLower );
    }
}
